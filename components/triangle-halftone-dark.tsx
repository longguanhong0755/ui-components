function clampN(v: unknown, lo: number, hi: number, d: number): number {
    return Math.max(lo, Math.min(hi, num(v, d)))
}

/** Extra uniforms for this effect, set every frame. */
function effectUniforms(gl: WebGL2RenderingContext, u: (name: string) => WebGLUniformLocation | null, p: Props): void {
    const adv = { ...ADVANCED_DEFAULTS, ...(p.advanced ?? {}) }
    const density = clampN(p.density, 0, 100, 50)
    const motion = clampN(p.motion, 0, 100, 50) / 50
    gl.uniform4f(
        u("uLat"),
        clampN(adv.cellSize, 10, 400, 105) / 1000,
        clampN(adv.maxSize, 0, 100, 75) / 100,
        Math.max(0.1, clampN(adv.edgeSoft, 10, 400, 100) / 100),
        ((density - 50) / 100) * 0.8
    )
    gl.uniform4f(
        u("uBand"),
        clampN(adv.bandStart, -100, 300, 5) / 100,
        clampN(adv.bandFull, -100, 300, 65) / 100,
        clampN(adv.bandEnd, -100, 300, 120) / 100,
        clampN(adv.bandCut, -100, 300, 150) / 100
    )
    gl.uniform4f(
        u("uBand2"),
        (clampN(adv.bandAngle, -180, 180, 32) * Math.PI) / 180,
        clampN(adv.tailSize, 0, 100, 55) / 100,
        clampN(adv.tailStart, -100, 300, -10) / 100,
        clampN(adv.tailEnd, -100, 300, 90) / 100
    )
    gl.uniform2f(u("uEdge"), clampN(adv.edgeFade, 0, 100, 25) / 100, clampN(adv.edgeFloor, 0, 100, 30) / 100)
    gl.uniform4f(
        u("uNoise"),
        clampN(adv.noiseAmp, 0, 100, 14) / 100,
        clampN(adv.noiseFreq, 1, 100, 18) / 10,
        (clampN(adv.noiseTravel, 0, 300, 60) / 100) * motion,
        (clampN(adv.drift, 0, 50, 10) / 100) * motion
    )
    gl.uniform1f(u("uPeriod"), clampN(adv.periodS, 1, 120, 12))
    gl.uniform3f(
        u("uPtr"),
        (clampN(adv.hoverRadius, 1, 100, 15) / 100) * 0.5,
        clampN(adv.hoverBoost, 0, 100, 30) / 100,
        clampN(adv.hover, 0, 100, 50) / 50
    )
    gl.uniform2f(u("uFx"), clampN(adv.grain, 0, 100, 0) / 100, clampN(adv.vignette, 0, 100, 0) / 100)
}

/* Triangle halftone: equilateral tessellation, each triangle scaled about its centroid by a
   size field (diagonal band + soft noise) sampled once per cell. The lattice and the field are
   both measured in frame widths and the field is centred vertically, so any frame shows the
   reference as a cover-fitted crop (a 1027×1892 frame shows it whole). The field drifts on a
   closed circle so one period loops seamlessly; the pointer swells nearby triangles. */
const FRAG = `#version 300 es
precision highp float;
uniform vec2 uRes;
uniform float uTime;
uniform vec2 uMouse;
uniform float uHover;
uniform vec3 uBg;
uniform vec3 uBase;
uniform vec3 uAccent;
uniform float uScale;
uniform vec4 uLat;
uniform vec4 uBand;
uniform vec4 uBand2;
uniform vec2 uEdge;
uniform vec4 uNoise;
uniform float uPeriod;
uniform vec3 uPtr;
uniform vec2 uFx;
out vec4 outColor;

const float TAU = 6.28318530718;
const float R3H = 0.86602540378;

vec3 mod289(vec3 x) { return x - floor(x * (1.0 / 289.0)) * 289.0; }
vec4 mod289(vec4 x) { return x - floor(x * (1.0 / 289.0)) * 289.0; }
vec4 permute(vec4 x) { return mod289(((x * 34.0) + 1.0) * x); }
vec4 taylorInvSqrt(vec4 r) { return 1.79284291400159 - 0.85373472095314 * r; }
float snoise(vec3 v) {
    const vec2 C = vec2(1.0 / 6.0, 1.0 / 3.0);
    const vec4 D = vec4(0.0, 0.5, 1.0, 2.0);
    vec3 i = floor(v + dot(v, C.yyy));
    vec3 x0 = v - i + dot(i, C.xxx);
    vec3 g = step(x0.yzx, x0.xyz);
    vec3 l = 1.0 - g;
    vec3 i1 = min(g.xyz, l.zxy);
    vec3 i2 = max(g.xyz, l.zxy);
    vec3 x1 = x0 - i1 + C.xxx;
    vec3 x2 = x0 - i2 + C.yyy;
    vec3 x3 = x0 - D.yyy;
    i = mod289(i);
    vec4 p = permute(permute(permute(i.z + vec4(0.0, i1.z, i2.z, 1.0)) + i.y + vec4(0.0, i1.y, i2.y, 1.0)) + i.x + vec4(0.0, i1.x, i2.x, 1.0));
    float n_ = 0.142857142857;
    vec3 ns = n_ * D.wyz - D.xzx;
    vec4 j = p - 49.0 * floor(p * ns.z * ns.z);
    vec4 x_ = floor(j * ns.z);
    vec4 y_ = floor(j - 7.0 * x_);
    vec4 x = x_ * ns.x + ns.yyyy;
    vec4 y = y_ * ns.x + ns.yyyy;
    vec4 h = 1.0 - abs(x) - abs(y);
    vec4 b0 = vec4(x.xy, y.xy);
    vec4 b1 = vec4(x.zw, y.zw);
    vec4 s0 = floor(b0) * 2.0 + 1.0;
    vec4 s1 = floor(b1) * 2.0 + 1.0;
    vec4 sh = -step(h, vec4(0.0));
    vec4 a0 = b0.xzyw + s0.xzyw * sh.xxyy;
    vec4 a1 = b1.xzyw + s1.xzyw * sh.zzww;
    vec3 p0 = vec3(a0.xy, h.x);
    vec3 p1 = vec3(a0.zw, h.y);
    vec3 p2 = vec3(a1.xy, h.z);
    vec3 p3 = vec3(a1.zw, h.w);
    vec4 norm = taylorInvSqrt(vec4(dot(p0, p0), dot(p1, p1), dot(p2, p2), dot(p3, p3)));
    p0 *= norm.x; p1 *= norm.y; p2 *= norm.z; p3 *= norm.w;
    vec4 m = max(0.6 - vec4(dot(x0, x0), dot(x1, x1), dot(x2, x2), dot(x3, x3)), 0.0);
    m = m * m;
    return 42.0 * dot(m * m, vec4(dot(p0, x0), dot(p1, x1), dot(p2, x2), dot(p3, x3)));
}

// Size field at a triangle centroid (px, y down). 0 = empty cell, 1 = full size.
float field(vec2 c, float th) {
    float W = max(uRes.x, 1.0);
    // Reference space in frame widths: x 0..1 across, y 0..1.84 down (the portrait
    // reference), centred vertically on the frame.
    vec2 q = vec2(c.x / W, (c.y - 0.5 * uRes.y) / W + 0.92);
    float ux = q.x;
    vec2 nrm = vec2(cos(uBand2.x), sin(uBand2.x)); // across the band, toward lower-right
    vec2 axs = vec2(-nrm.y, nrm.x);                 // along the band, toward lower-left
    // Closed drift loop: rest at th = 0, furthest (= drift) at th = pi, down the band.
    q -= uNoise.w * 0.5 * ((1.0 - cos(th)) * axs + 0.5 * sin(th) * nrm);
    float pa = dot(q, nrm);
    float al = dot(q, axs);
    float rise = smoothstep(uBand.x, max(uBand.y, uBand.x + 1e-4), pa);
    float fall = 1.0 - smoothstep(uBand.z, max(uBand.w, uBand.z + 1e-4), pa);
    float tail = mix(1.0, uBand2.y, smoothstep(uBand2.z, max(uBand2.w, uBand2.z + 1e-4), al));
    float edge = mix(uEdge.y, 1.0, smoothstep(0.0, max(uEdge.x, 1e-4), ux));
    float base = rise * fall * tail * edge;
    float r = uNoise.z;
    vec3 np = vec3(q * uNoise.y, 0.0) + vec3(r * (cos(th) - 1.0), 0.0, r * sin(th));
    float nz = snoise(np);
    return base + uNoise.x * nz * (0.4 + 0.6 * base);
}

float hash(vec2 p) { return fract(sin(dot(p, vec2(12.9898, 78.233))) * 43758.5453); }

void main() {
    vec2 px = vec2(gl_FragCoord.x, uRes.y - gl_FragCoord.y);
    // Triangle side as a fraction of the frame width (reference: ~10.5% of its width).
    float L = max(uLat.x * uRes.x * uScale, 4.0);
    float Ht = L * R3H;
    float row = floor(px.y / Ht);
    float fy = px.y / Ht - row;
    float xs = px.x / L + row * 0.5;
    float c = floor(xs);
    float fx = xs - c;
    bool up = abs(fx - 0.5) < fy * 0.5;
    vec2 cen;
    if (up) {
        cen = vec2((c + 0.5 - row * 0.5) * L, (row + 2.0 / 3.0) * Ht);
    } else {
        float k = fx < 0.5 ? c : c + 1.0;
        cen = vec2((k - row * 0.5) * L, (row + 1.0 / 3.0) * Ht);
    }

    float th = TAU * uTime / max(uPeriod, 0.5);
    float n = field(cen, th) + uLat.w;
    vec2 mp = vec2(uMouse.x, 1.0 - uMouse.y) * uRes;
    float sig = max(uPtr.x * uRes.x, 1.0);
    vec2 dm = cen - mp;
    n += uPtr.y * uPtr.z * uHover * exp(-dot(dm, dm) / (2.0 * sig * sig));
    n = clamp(n, 0.0, 1.0);

    float s = uLat.y * n;
    vec2 p = px - cen;
    if (!up) p.y = -p.y;
    float ri = s * L * 0.28867513459;
    float d = max(p.y, max(dot(p, vec2(-R3H, -0.5)), dot(p, vec2(R3H, -0.5)))) - ri;
    float alpha = clamp(0.5 - d / max(uLat.z, 1e-3), 0.0, 1.0) * smoothstep(0.0, 1.0, ri);

    vec3 tri = mix(uBase, uAccent, n);
    vec3 col = mix(uBg, tri, alpha);

    vec2 vv = gl_FragCoord.xy / max(uRes, vec2(1.0)) - 0.5;
    col *= 1.0 - uFx.y * 0.8 * smoothstep(0.2, 0.85, length(vv) * 1.2);
    col += (hash(px + floor(uTime * 24.0) * vec2(17.0, 31.0)) - 0.5) * uFx.x * 0.35;
    outColor = vec4(clamp(col, 0.0, 1.0), 1.0);
}`

// ══ /EFFECT ═════════════════════════════════════════════════════════════════

interface Props extends EffectProps {
    background?: string
    baseColor?: string
    accentColor?: string
    speed?: number
    scale?: number
    style?: CSSProperties
}

function num(v: unknown, d: number): number {
    return typeof v === "number" && Number.isFinite(v) ? v : d
}

const VERT = `#version 300 es
in vec2 aPos;
void main() { gl_Position = vec4(aPos, 0.0, 1.0); }`

export default function TriangleHalftoneDark(props: Props) {
    props = withMovedControls(props)
    // Read live from propsRef; destructured here so their defaults sit in the signature.
    const { background = "#000000", baseColor = "#000000", accentColor = "#FFFFFF", speed = 100, scale = 36, style } = props
    void [baseColor, accentColor, speed, scale]
    const rootRef = useRef<HTMLDivElement>(null)
    const canvasRef = useRef<HTMLCanvasElement>(null)
    const propsRef = useRef(props)
    propsRef.current = props

    useEffect(() => {
        const root = rootRef.current
        const canvas = canvasRef.current
        if (!root || !canvas) return
        const gl = canvas.getContext("webgl2", { alpha: false, antialias: false, depth: false })
        if (!gl) return
        const reduced = typeof window.matchMedia === "function" && window.matchMedia("(prefers-reduced-motion: reduce)").matches

        const sh = (type: number, src: string) => {
            const s = gl.createShader(type)!
            gl.shaderSource(s, src)
            gl.compileShader(s)
            if (!gl.getShaderParameter(s, gl.COMPILE_STATUS)) console.error("TriangleHalftoneDark shader:", gl.getShaderInfoLog(s))
            return s
        }
        const prog = gl.createProgram()!
        gl.attachShader(prog, sh(gl.VERTEX_SHADER, VERT))
        gl.attachShader(prog, sh(gl.FRAGMENT_SHADER, FRAG))
        gl.linkProgram(prog)
        if (!gl.getProgramParameter(prog, gl.LINK_STATUS)) {
            console.error("TriangleHalftoneDark link:", gl.getProgramInfoLog(prog))
            return
        }
        gl.useProgram(prog)
        const buf = gl.createBuffer()
        gl.bindBuffer(gl.ARRAY_BUFFER, buf)
        gl.bufferData(gl.ARRAY_BUFFER, new Float32Array([-1, -1, 3, -1, -1, 3]), gl.STATIC_DRAW)
        const loc = gl.getAttribLocation(prog, "aPos")
        gl.enableVertexAttribArray(loc)
        gl.vertexAttribPointer(loc, 2, gl.FLOAT, false, 0, 0)
        const cache = new Map<string, WebGLUniformLocation | null>()
        const u = (name: string) => {
            if (!cache.has(name)) cache.set(name, gl.getUniformLocation(prog, name))
            return cache.get(name) ?? null
        }

        let W = 0
        let H = 0
        const resize = () => {
            W = root.offsetWidth
            H = root.offsetHeight
            const dpr = Math.min(window.devicePixelRatio || 1, 2)
            canvas.width = Math.max(1, Math.round(W * dpr))
            canvas.height = Math.max(1, Math.round(H * dpr))
        }
        const ro = new ResizeObserver(resize)
        ro.observe(root)
        resize()

        let mx = 0.5
        let my = 0.5
        let tx = 0.5
        let ty = 0.5
        let over = 0
        let hov = 0
        const onMove = (e: PointerEvent) => {
            if (W <= 0 || H <= 0) return
            tx = e.offsetX / W
            ty = 1 - e.offsetY / H
            over = 1
        }
        const onLeave = () => {
            over = 0
        }
        canvas.addEventListener("pointermove", onMove)
        canvas.addEventListener("pointerleave", onLeave)

        let clock = 0
        let raf = 0
        let last = -1
        const frame = (now: number) => {
            raf = requestAnimationFrame(frame)
            const dt = last < 0 ? 0 : Math.min((now - last) / 1000, 1 / 20)
            last = now
            const p = propsRef.current
            clock = (clock + dt * (Math.max(0, Math.min(100, num(p.speed, 50))) / 50) * (reduced ? 0.25 : 1)) % 3600
            const k = 1 - Math.exp(-dt * 6)
            mx += (tx - mx) * k
            my += (ty - my) * k
            hov += (over - hov) * k
            const bg = parseColor(p.background, [0.03, 0.03, 0.04, 1])
            const base = parseColor(p.baseColor, [0.23, 0.18, 0.55, 1])
            const acc = parseColor(p.accentColor, [0.91, 0.42, 0.57, 1])
            gl.viewport(0, 0, canvas.width, canvas.height)
            gl.uniform2f(u("uRes"), canvas.width, canvas.height)
            gl.uniform1f(u("uTime"), clock)
            gl.uniform2f(u("uMouse"), mx, my)
            // Raw 0..1: the FRAG scales it by the Advanced `hover` row (RULES.md).
            gl.uniform1f(u("uHover"), hov)
            gl.uniform3f(u("uBg"), bg[0], bg[1], bg[2])
            gl.uniform3f(u("uBase"), base[0], base[1], base[2])
            gl.uniform3f(u("uAccent"), acc[0], acc[1], acc[2])
            gl.uniform1f(u("uScale"), Math.max(10, Math.min(300, num(p.scale, 100))) / 100)
            effectUniforms(gl, u, p)
            gl.drawArrays(gl.TRIANGLES, 0, 3)
        }
        raf = requestAnimationFrame(frame)
        return () => {
            cancelAnimationFrame(raf)
            ro.disconnect()
            canvas.removeEventListener("pointermove", onMove)
            canvas.removeEventListener("pointerleave", onLeave)
        }
    }, [])

    return (
        <div ref={rootRef} style={{ position: "relative", minWidth: 1200, minHeight: 800, overflow: "hidden", background, ...style }}>
            <canvas ref={canvasRef} style={{ position: "absolute", inset: 0, width: "100%", height: "100%", display: "block" }} />
        </div>
    )
}
